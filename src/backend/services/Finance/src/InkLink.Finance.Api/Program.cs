using InkLink.Finance.Api.Extensions;
using InkLink.Finance.Infrastructure;
using InkLink.Observability;
var builder = WebApplication.CreateBuilder(args);
builder.Logging.AddFinanceLogging();
builder.Services.AddFinanceInfrastructure(builder.Configuration);
builder.Services.AddFinanceUseCases();
builder.Services.AddFinanceAuthentication(builder.Configuration, builder.Environment);
builder.Services.AddIdentityIntegration(builder.Configuration, builder.Environment);
builder.Services.AddFinanceSources(builder.Configuration, builder.Environment);
builder.Services.AddFinanceHttpContracts();
builder.Services.AddFinanceDocumentation();
var app = builder.Build();
app.UseCorrelatedRequestLogging();
app.UseFinanceHttpErrors();
app.UseFinanceAuthentication();
app.MapFinanceHealth();
app.MapFinanceDocumentation();
app.MapFinanceLedger();
app.Run();
